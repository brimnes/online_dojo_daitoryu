-- 011: последовательность номеров счетов для Робокассы
-- Робокасса требует InvId — целое число, уникальное в рамках магазина
-- (наш Payment.id — UUID, для InvId не подходит).
-- Стартуем с 100000, чтобы не пересекаться с любыми тестовыми значениями.
CREATE SEQUENCE IF NOT EXISTS robokassa_inv_seq START 100000;
